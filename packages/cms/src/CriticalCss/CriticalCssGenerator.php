<?php

declare(strict_types=1);

namespace Itk\Cms\CriticalCss;

use Doctrine\DBAL\Connection;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\EntityManagerInterface;
use Itk\Cms\CriticalCss\Model\Basis;
use Itk\Cms\CriticalCss\Model\CriticalStyles;
use Itk\Cms\CriticalCss\Model\ExtractedCss;
use Itk\Cms\CriticalCss\Model\Freshness;
use Itk\Cms\CriticalCss\Model\GenerationReport;
use Itk\Cms\CriticalCss\Model\SourceCss;
use Itk\Cms\CriticalCss\Model\SourcePage;
use Itk\Cms\CriticalCss\Model\When;
use Itk\Cms\Entity\CriticalCss;
use Itk\Cms\Entity\PageTranslation;
use Itk\Cms\I18n\ContentLocales;
use Itk\Cms\Rendering\PageRenderer;
use Psr\Clock\ClockInterface;
use Psr\Log\LoggerInterface;

/**
 * Critical CSS of live pages, worker side (the message handler and the command --now): render each page in PHP, hand the pages to the CssExtractor,
 * store each result as it comes. The one writer of itk_critical_css.
 *
 * @internal
 */
final class CriticalCssGenerator
{
    public function __construct(
        private readonly EntityManagerInterface $em,
        private readonly Connection $db,
        private readonly CriticalCssService $critical,
        private readonly Stylesheets $stylesheets,
        private readonly PageRenderer $renderer,
        private readonly CssExtractor $extractor,
        private readonly ClockInterface $clock,
        private readonly LoggerInterface $logger,
        private readonly ?ContentLocales $contentLocales = null,
    ) {
    }

    /**
     * CLI only: it throws LogicException inside a web request.
     * Idempotent: everything is derived from the rows and the pages as they are now; a crash leaves the pages done so far stored and the rest Stale.
     *
     * @param array<string, When> $ids translation id => which states still run
     */
    public function generate(array $ids): GenerationReport
    {
        if ('cli' !== \PHP_SAPI) {
            throw new \LogicException('Critical CSS is generated by the worker or the console only, never inside a web request.');
        }
        $generated = $reused = $skipped = 0;
        $failed = [];
        $cssProblem = null;
        $css = '';
        $stamp = $this->critical->stamp();
        try {
            $css = $this->stylesheets->sourceCss();
        } catch (\RuntimeException $e) {
            $cssProblem = $e->getMessage();
        }
        $lossy = SourceCss::lossy($css);
        if ([] !== $lossy) {
            $this->logger->warning('The stylesheets use {features}, which crittr drops from the critical CSS: the first paint may differ until the full stylesheet loads.', ['features' => \implode(', ', $lossy)]);
        }
        $viewports = $this->stylesheets->viewports();
        $config = $this->stylesheets->generatorConfig();

        /** @var array<string, array{0: PageTranslation, 1: Basis, 2: string, 3: SourcePage}> $todo */
        $todo = [];
        foreach ($ids as $id => $when) {
            $t = $this->em->find(PageTranslation::class, $id);
            if (null === $t || !$t->isLive() || !($this->contentLocales?->has($t->locale) ?? true)) {
                ++$skipped;
                continue;
            }
            $basis = $this->critical->wanted($t);
            $row = $this->em->find(CriticalCss::class, $t->id);
            if (!$when->admits(Freshness::of($row, $basis))) {
                ++$skipped;
                continue;
            }
            if (null !== $cssProblem) {
                $this->store($t, $row, $basis, '', $cssProblem, $stamp);
                $failed[$t->id] = $cssProblem;
                continue;
            }
            try {
                $html = $this->renderer->renderSource($t);
            } catch (\Throwable $e) {
                $reason = 'render: ' . $e->getMessage();
                $this->store($t, $row, $basis, '', $reason, $stamp);
                $failed[$t->id] = $reason;
                continue;
            }
            $inputs = \sha1($html . "\x1f" . $css . "\x1f" . $config);
            if ($when->reusesIdenticalInputs() && null !== $row && CriticalCss::READY === $row->status && $row->inputs === $inputs && null !== $row->styles && [] !== $row->styles) {
                $this->store($t, $row, $basis, $inputs, CriticalStyles::fromStored($row->styles), $stamp);
                ++$reused;
                continue;
            }
            $path = (string) ($t->published['url'] ?? '/');
            $todo[$t->id] = [$t, $basis, $inputs, new SourcePage($t->id, '' === $path ? '/' : $path, $html)];
        }
        if ([] !== $todo) {
            $pages = \array_values(\array_map(static fn (array $job): SourcePage => $job[3], $todo));
            foreach ($this->extractor->extract($css, $viewports, $pages) as $id => $result) {
                if (!isset($todo[$id])) {
                    continue;
                }
                [$t, $basis, $inputs] = $todo[$id];
                unset($todo[$id]);
                $styles = $result instanceof ExtractedCss ? CriticalStyles::fromRuns($viewports, $result->cssPerViewport, $this->stylesheets->maxBytes()) : $result->reason;
                $this->store($t, $this->em->find(CriticalCss::class, $t->id), $basis, $inputs, $styles, $stamp);
                if ($styles instanceof CriticalStyles) {
                    ++$generated;
                } else {
                    $failed[$t->id] = $styles;
                }
            }
        }

        return new GenerationReport($generated, $reused, $skipped, $failed);
    }

    /**
     * Writes the row with one upsert keyed by the translation: two workers on the same page never meet a UniqueConstraintViolation that would close the
     * EntityManager.
     */
    private function store(PageTranslation $t, ?CriticalCss $row, Basis $basis, string $inputs, CriticalStyles|string $outcome, string $stamp): void
    {
        $row ??= CriticalCss::for($t);
        $now = $this->clock->now();
        if ($outcome instanceof CriticalStyles) {
            $row->markReady($basis->value, $inputs, $outcome->toStored(), $now, $stamp);
        } else {
            $row->markFailed($basis->value, $inputs, $outcome, $now);
        }
        $this->db->executeStatement(
            'INSERT INTO itk_critical_css (translation_id, basis, stamp, inputs, status, styles, error, generated_at) VALUES (:id, :basis, :stamp, :inputs, :status, :styles, :error, :at)
                ON CONFLICT (translation_id) DO UPDATE SET basis = EXCLUDED.basis, stamp = EXCLUDED.stamp, inputs = EXCLUDED.inputs, status = EXCLUDED.status, styles = EXCLUDED.styles, error = EXCLUDED.error, generated_at = EXCLUDED.generated_at',
            ['id' => $t->id, 'basis' => $row->basis, 'stamp' => $row->stamp, 'inputs' => $row->inputs, 'status' => $row->status, 'styles' => $row->styles, 'error' => $row->error, 'at' => $row->generatedAt],
            ['styles' => Types::JSON, 'at' => Types::DATETIME_IMMUTABLE],
        );
        $this->em->detach($row);
    }
}
